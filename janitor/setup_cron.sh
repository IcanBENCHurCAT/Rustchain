#!/usr/bin/env bash
# 🧹 Janitor — Setup Weekly Cron Job
# Installs a crontab entry that runs the janitor sweep every Monday at 09:00 ET
#
# Usage: bash setup_cron.sh          # Install the cron job
#        bash setup_cron.sh --remove  # Remove the cron job

JANITOR_DIR="$(cd "$(dirname "$0")" && pwd)"
JANITOR_PY="${JANITOR_DIR}/janitor.py"
CRON_LABEL="# JANITOR CRON — auto-generated by setup_cron.sh"

add_cron() {
    # Current crontab (may be empty)
    local current
    current=$(crontab -l 2>/dev/null)

    # Remove any existing janitor cron entries
    if [ -n "$current" ]; then
        current=$(echo "$current" | grep -v "janitor.py" | grep -v "JANITOR CRON")
    fi

    # Add new entry: Monday 09:00 ET = 14:00 UTC
    # Minute  Hour  DayOfMonth  Month  DayOfWeek  Command
    local new_entry="0 14 * * 1 ${JANITOR_PY} sweep >> \"${JANITOR_DIR}/sweep.log\" 2>&1"

    local final="${CRON_LABEL}\n${new_entry}"

    if [ -z "$current" ]; then
        echo "$final" | crontab -
    else
        echo -e "${current}\n${CRON_LABEL}\n${new_entry}" | crontab -
    fi

    echo "✅ Janitor cron job installed:"
    echo "   Schedule: Monday 09:00 Eastern (14:00 UTC)"
    echo "   Command: ${JANITOR_PY} sweep"
    echo "   Log: ${JANITOR_DIR}/sweep.log"
    echo ""
    echo "   Full crontab:"
    crontab -l
}

remove_cron() {
    local current
    current=$(crontab -l 2>/dev/null) || true

    if [ -z "$current" ]; then
        echo "ℹ️  No existing crontab found."
        return
    fi

    # Remove janitor lines
    local filtered
    filtered=$(echo "$current" | grep -v "janitor.py" | grep -v "JANITOR CRON")

    if [ -z "$filtered" ]; then
        crontab -r 2>/dev/null || echo "Removed all crontab entries."
        echo "🗑️  Crontab cleared (no janitor-specific entries found)."
    else
        echo "$filtered" | crontab -
        echo "🗑️  Janitor cron entry removed."
        echo ""
        echo "   Remaining crontab:"
        crontab -l
    fi
}

case "${1:-}" in
    --remove|-r)
        remove_cron
        ;;
    *)
        add_cron
        ;;
esac
