#!/usr/bin/env python3
"""
Janitor System -- Cron Setup / Management

Manages a weekly cron job that runs the Janitor sweep automatically.

Usage:
    python3 cron_setup.py              # Install the weekly cron job
    python3 cron_setup.py --dry-run    # Show what would be installed (no changes)
    python3 cron_setup.py --uninstall  # Remove the Janitor cron entry
    python3 cron_setup.py --status     # Show current cron state
"""

import os
import re
import sys
import subprocess
import logging
from datetime import datetime, timezone, timedelta
from pathlib import Path

# ------------------------------------------------------------------ Constants

JANITOR_DIR = Path(__file__).resolve().parent
JANITOR_PY = JANITOR_DIR / "janitor.py"

# Sunday 03:00 Eastern = 08:00 UTC
CRON_MINUTE = "0"
CRON_HOUR = "8"
CRON_DOW = "0"  # Sunday

CRON_LABEL = "# JANITOR CRON -- auto-generated by cron_setup.py"
SWEEP_LOG = JANITOR_DIR / "sweep.log"

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%Y-%m-%d %H:%M",
)
log = logging.getLogger("janitor-cron")


# ------------------------------------------------------------------ Helpers

def _get_crontab():
    """Return the current user crontab content, or empty string if none."""
    try:
        result = subprocess.run(
            ["crontab", "-l"],
            capture_output=True, text=True, timeout=10,
        )
        if result.returncode == 0:
            return result.stdout
    except (subprocess.SubprocessError, FileNotFoundError):
        pass
    return ""


def _install_crontab(content):
    """Write content to the user crontab via crontab -."""
    proc = subprocess.run(
        ["crontab", "-"],
        input=content, text=True, capture_output=True, timeout=10,
    )
    if proc.returncode != 0:
        log.error("crontab - failed: %s", proc.stderr.strip())
        raise RuntimeError("Failed to install crontab entry")


def _filter_out_janitor(text):
    """Remove any existing Janitor cron lines from crontab text."""
    out_lines = []
    for raw_line in text.splitlines(keepends=True):
        stripped = raw_line.rstrip("\n")
        if "janitor.py" not in stripped and "JANITOR CRON" not in stripped:
            out_lines.append(raw_line)
    return "".join(out_lines)


def _build_cron_entry():
    """Return the full cron line for the weekly janitor sweep."""
    cmd = str(JANITOR_PY) + " sweep"
    return (
        CRON_MINUTE + " " + CRON_HOUR + " * * " + CRON_DOW + " " + cmd
        + ' >> "' + str(SWEEP_LOG) + '" 2>&1 # ' + CRON_LABEL
    )


def _parse_cron_line(line):
    """Parse a cron line and return a dict, or None if not a janitor entry."""
    if "janitor.py" not in line or "JANITOR CRON" not in line:
        return None
    pattern = (
        r"^(\d+)\s+(\d+)\s+(\S+)\s+(\S+)\s+(\d*)\s+"
        r"(.+?)(?:\s+#\s*(.*))?$"
    )
    m = re.search(pattern, line)
    if not m:
        return {"raw": line}
    return {
        "minute": m.group(1),
        "hour": m.group(2),
        "dom": m.group(3),
        "month": m.group(4),
        "dow": m.group(5) or "*",
        "command": m.group(6),
        "label": m.group(7) or "",
    }


# ------------------------------------------------------------------ Commands

def cmd_dry_run():
    """Show what the cron job would install without touching the system."""
    log.info("--- DRY RUN: What would be installed ---")

    entry = _build_cron_entry()
    parsed = _parse_cron_line(entry)
    if parsed is None:
        parsed = {}

    print()
    print("  Janitor cron job (DRY RUN)")
    print("  " + "=" * 46)
    print(
        "  Schedule : Every Sunday at "
        + parsed.get("hour", CRON_HOUR) + ":"
        + parsed.get("minute", CRON_MINUTE) + " UTC"
    )
    print("            (Sunday 03:00 Eastern)")
    print("  Command  : " + parsed.get("command", ""))
    print("  Log file : " + str(SWEEP_LOG))
    print("  Cron line: " + entry)
    print()

    existing = _get_crontab()
    janitor_lines = [l for l in existing.splitlines() if "janitor.py" in l]

    if janitor_lines:
        print("  WARNING: Existing Janitor entries found in crontab:")
        for ln in janitor_lines:
            print("    " + ln)
        print("  Would be REPLACED by the new entry above.")
    else:
        print("  OK -- No existing Janitor cron entry detected.")

    print()
    print("  To install, run:  python3 cron_setup.py")
    log.info("Dry run complete -- no changes made.")
    return 0


def cmd_install():
    """Install the weekly Janitor cron job."""
    entry = _build_cron_entry()
    existing = _get_crontab()

    # Remove old Janitor lines
    filtered = _filter_out_janitor(existing)

    # Append the new entry
    new_lines = []
    if filtered.strip():
        new_lines = filtered.strip().splitlines()
    new_lines.append(CRON_LABEL)
    new_lines.append(entry)
    new_content = "\n".join(new_lines) + "\n"

    _install_crontab(new_content)

    log.info("Janitor cron job installed.")
    print()
    print("  OK  Janitor cron job installed")
    print("  " + "=" * 46)
    print("  Schedule : Every Sunday at 03:00 Eastern (08:00 UTC)")
    print("  Command  : " + str(JANITOR_PY) + " sweep")
    print("  Log file : " + str(SWEEP_LOG))
    print()
    print("  Current crontab:")
    print("  " + "-" * 46)
    try:
        result = subprocess.run(
            ["crontab", "-l"], capture_output=True, text=True, timeout=10
        )
        if result.returncode == 0:
            for line in result.stdout.splitlines():
                print("    " + line)
        else:
            print("    (empty)")
    except Exception:
        print("    (unable to read crontab)")
    print("  " + "-" * 46)
    print()

    # Verify the entry is present
    verify = _get_crontab()
    if "janitor.py" not in verify:
        log.error("Verification failed: janitor.py not found in crontab")
        return 1

    log.info("Cron installation verified.")
    return 0


def cmd_uninstall():
    """Remove the Janitor cron job from crontab."""
    existing = _get_crontab()
    janitor_lines = [l for l in existing.splitlines() if "janitor.py" in l]

    if not janitor_lines:
        log.info("No Janitor cron entry found -- nothing to remove.")
        print("  INFO -- No Janitor cron entry found.")
        return 0

    filtered = _filter_out_janitor(existing)
    if not filtered.strip():
        subprocess.run(["crontab", "-r"], capture_output=True, timeout=10)
        log.info("Crontab removed (no non-cron entries remain).")
        print("  CRONTAB cleared (no Janitor entries left).")
    else:
        _install_crontab(filtered)
        log.info("Janitor cron entry removed.")
        print("  Janitor cron entry removed.")
        print()
        print("  Remaining crontab:")
        print("  " + "-" * 46)
        result = subprocess.run(
            ["crontab", "-l"], capture_output=True, text=True, timeout=10
        )
        if result.returncode == 0:
            for line in result.stdout.splitlines():
                print("    " + line)
        print("  " + "-" * 46)

    return 0


def cmd_status():
    """Show the current Janitor cron state."""
    existing = _get_crontab()
    janitor_lines = [l for l in existing.splitlines() if "janitor.py" in l]

    print()
    print("  Janitor Cron Status")
    print("  " + "=" * 46)

    now_utc = datetime.now(tz=timezone.utc)
    print("  Current time : " + now_utc.strftime("%Y-%m-%d %H:%M UTC"))
    print()

    if janitor_lines:
        print("  OK  Janitor cron job is INSTALLED")
        print()
        for line in janitor_lines:
            print("    " + line)
        print()

        parsed = _parse_cron_line(janitor_lines[0])
        if parsed:
            next_run = _estimate_next_run(parsed)
            print("  Next scheduled run: " + next_run)
    else:
        print("  INFO -- No Janitor cron entry found.")
        print("  To install:  python3 cron_setup.py")

    if SWEEP_LOG.exists():
        size = SWEEP_LOG.stat().st_size
        print("")
        print("  Sweep log: " + str(SWEEP_LOG) + " (" + str(size) + " bytes)")
    else:
        print("")
        print("  Sweep log: " + str(SWEEP_LOG) + " (not yet created)")

    print()
    return 0


def _estimate_next_run(parsed):
    """Rough estimate of the next run time for a cron expression."""
    try:
        hour_num = int(parsed.get("hour", "8"))
        minute_num = int(parsed.get("minute", "0"))

        now = datetime.now(tz=timezone.utc).replace(
            minute=minute_num, second=0, microsecond=0
        )

        # Python: Monday=0, Sunday=6
        days_ahead = (6 - now.weekday()) % 7
        if days_ahead == 0 and now.hour >= hour_num:
            days_ahead = 7

        next_dt = now.replace(hour=hour_num, minute=minute_num)
        next_dt = next_dt + timedelta(days=days_ahead)

        # Approximate Eastern (UTC-5 EST)
        est_offset = timedelta(hours=-5)
        next_et = next_dt + est_offset
        return next_et.strftime("%Y-%m-%d %H:%M Eastern")
    except Exception:
        return "(unknown)"


# ------------------------------------------------------------------ Main

def main():
    args = sys.argv[1:]

    if "-h" in args or "--help" in args:
        print(__doc__.strip())
        return 0

    if "--dry-run" in args or "-n" in args:
        return cmd_dry_run()

    if "--uninstall" in args or "-u" in args:
        return cmd_uninstall()

    if "--status" in args or "-s" in args:
        return cmd_status()

    if "--install" in args or "-i" in args:
        return cmd_install()

    # Default: install
    return cmd_install()


if __name__ == "__main__":
    sys.exit(main())
